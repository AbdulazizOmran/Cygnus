def build_flatpak_bundle(dest: Path, *, runtime="org.cygnus.TestPlatform/x86_64/1",
                         origin_url: str | None = None) -> Path:
    """Build a real single-file bundle from a hand-made OSTree commit (no SDK, no installation)."""
    ostree, flatpak = shutil.which("ostree"), shutil.which("flatpak")
    if not ostree or not flatpak:
        raise RuntimeError("ostree and flatpak are required")
    app = dest / "app"
    (app / "files/bin").mkdir(parents=True)
    metadata = (f"[Application]\nname=org.cygnus.TestApp\nruntime={runtime}\n"
                "sdk=org.cygnus.TestSdk/x86_64/1\ncommand=testapp\n\n[Context]\nshared=network;\n")
    (app / "metadata").write_text(metadata)
    exe = app / "files/bin/testapp"
    exe.write_text("#!/bin/sh\necho hi\n")
    exe.chmod(0o755)
    repo = dest / "repo"
    subprocess.run([ostree, "init", "--mode=archive-z2", f"--repo={repo}"], check=True)
    subprocess.run([ostree, "commit", f"--repo={repo}", "--branch=app/org.cygnus.TestApp/x86_64/stable",
                    f"--tree=dir={app}", "--subject=test", f"--add-metadata-string=xa.metadata={metadata}"],
                   check=True, capture_output=True)
    out = dest / "test.flatpak"
    argv = [flatpak, "build-bundle", str(repo), str(out), "org.cygnus.TestApp", "stable",
            "--runtime-repo=https://example.invalid/test.flatpakrepo"]
    if origin_url:
        argv.append(f"--repo-url={origin_url}")
    env = {"FLATPAK_USER_DIR": str(dest / "fp-user"), "PATH": "/usr/bin:/bin", "HOME": str(dest)}
    subprocess.run(argv, check=True, capture_output=True, env=env)
    return out


# -- Flatpak repositories ---------------------------------------------------------------------------
class GpgTestKey:
    """A throwaway signing key in its own GnuPG home (never the user's ~/.gnupg); use as a context
    manager so the agent it starts is always stopped."""

    def __init__(self, root: Path):
        self.home = root / "gnupg"
        self.home.mkdir(mode=0o700, parents=True)
        self._gpg = ["gpg", "--homedir", str(self.home), "--batch", "--pinentry-mode", "loopback", "--passphrase", ""]
        subprocess.run(self._gpg + ["--quick-gen-key", "Cygnus Test <test@example.invalid>", "ed25519", "sign",
                                    "never"], check=True, capture_output=True)
        colons = subprocess.run(self._gpg + ["--list-keys", "--with-colons"], capture_output=True, text=True,
                                check=True).stdout
        self.keyid = next(l.split(":")[9] for l in colons.splitlines() if l.startswith("fpr:"))
        self.public = root / "key.gpg"
        self.public.write_bytes(subprocess.run(self._gpg + ["--export", self.keyid], capture_output=True,
                                               check=True).stdout)

    def sign_args(self, prefix: str = "--gpg-") -> list[str]:
        return [f"{prefix}sign={self.keyid}", f"{prefix}homedir={self.home}"]

    def __enter__(self) -> GpgTestKey:
        return self

    def __exit__(self, *exc) -> None:
        subprocess.run(["gpgconf", "--homedir", str(self.home), "--kill", "all"], capture_output=True)


def build_flatpak_repo(root: Path, runtimes: dict[str, str | None], key: GpgTestKey | None = None,
                       apps: dict[str, str] | None = None, extensions: dict[str, str] | None = None) -> Path:
    """An archive repository holding empty runtimes, {"name/arch/branch": eol-reason-or-None}, and
    tiny apps, {"app.id": "runtime/arch/branch"} (branch "stable")."""
    repo = root / "repo"
    repo.mkdir(parents=True)
    subprocess.run(["ostree", "init", "--mode=archive-z2", f"--repo={repo}"], check=True)
    for runtime, eol in runtimes.items():
        tree = root / "trees" / runtime.replace("/", "_")
        (tree / "files").mkdir(parents=True)
        meta = f"[Runtime]\nname={runtime.split('/')[0]}\nruntime={runtime}\n"
        ext = (extensions or {}).get(runtime)  # an extension Flatpak installs along with the runtime
        if ext:
            meta += f"\n[Extension {ext}]\ndirectory=ext\nversion={runtime.split('/')[2]}\nautodelete=true\n"
        (tree / "metadata").write_text(meta)
        argv = ["ostree", "commit", f"--repo={repo}", f"--branch=runtime/{runtime}", f"--tree=dir={tree}",
                "--subject=test", f"--add-metadata-string=xa.metadata={meta}"]
        if eol:
            argv.append(f"--add-metadata-string=ostree.endoflife={eol}")
        subprocess.run(argv + (key.sign_args() if key else []), check=True, capture_output=True)
    for app_id, runtime in (apps or {}).items():
        tree = root / "trees" / app_id
        (tree / "files/bin").mkdir(parents=True)
        exe = tree / "files/bin/testapp"
        exe.write_text("#!/bin/sh\necho hi\n")
        exe.chmod(0o755)
        meta = f"[Application]\nname={app_id}\nruntime={runtime}\ncommand=testapp\n\n[Context]\nshared=network;\n"
        (tree / "metadata").write_text(meta)
        subprocess.run(["ostree", "commit", f"--repo={repo}", f"--branch=app/{app_id}/x86_64/stable",
                        f"--tree=dir={tree}", "--subject=test", f"--add-metadata-string=xa.metadata={meta}",
                        *(key.sign_args() if key else [])], check=True, capture_output=True)
    subprocess.run(["flatpak", "build-update-repo", *(key.sign_args() if key else []), str(repo)],
                   check=True, capture_output=True,
                   env={"FLATPAK_USER_DIR": str(root / "unused"), "PATH": "/usr/bin:/bin", "HOME": str(root)})
    return repo


def add_ostree_remote(installation_dir: Path, name: str, repo: Path, key: GpgTestKey | None) -> None:
    """Configure a remote directly in an installation's repository, the way a system administrator's
    `flatpak remote-add` leaves it (keyring stored as <repo>/<name>.trustedkeys.gpg)."""
    target = installation_dir / "repo"
    if not target.exists():
        installation_dir.mkdir(parents=True, exist_ok=True)
        subprocess.run(["ostree", "init", "--mode=bare-user-only", f"--repo={target}"], check=True)
    trust = [f"--gpg-import={key.public}"] if key else ["--no-gpg-verify"]
    subprocess.run(["ostree", "remote", "add", f"--repo={target}", *trust, name, f"file://{repo}"],
                   check=True, capture_output=True)
