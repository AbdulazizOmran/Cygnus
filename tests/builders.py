"""Generate small, well-formed (and deliberately malformed) package files for tests.

Nothing here touches the host: every builder writes into a caller-provided directory.
"""

from __future__ import annotations

import io
import shutil
import struct
import subprocess
import tarfile
from pathlib import Path


# -- Arch packages --------------------------------------------------------------------------------
def build_pkg(dest: Path, *, name="hello", version="1.0-1", arch="x86_64", depends=("glibc",),
              install_script: str | None = None, compression="zst", extra_pkginfo: str = "") -> Path:
    pkginfo = (
        f"# Generated by makepkg\npkgname = {name}\npkgbase = {name}\npkgver = {version}\n"
        f"pkgdesc = Test package {name}\nurl = https://example.invalid\nbuilddate = 1700000000\n"
        f"packager = Test <test@example.invalid>\nsize = 12345\narch = {arch}\nlicense = MIT\n"
        + "".join(f"depend = {d}\n" for d in depends)
        + "optdepend = foo: optional foo support\nprovides = libhello.so=1-64\n"
        + extra_pkginfo
    )
    path = dest / f"{name}-{version}-{arch}.pkg.tar.{compression}"
    mode = f"w:{compression}" if compression else "w"
    with tarfile.open(path, mode) as tar:
        members = [(".BUILDINFO", b"format = 2\n"), (".MTREE", b"#mtree\n"), (".PKGINFO", pkginfo.encode())]
        if install_script is not None:
            members.append((".INSTALL", install_script.encode()))
        members.append(("usr/bin/hello", b"#!/bin/sh\necho hello\n"))
        for member_name, data in members:
            info = tarfile.TarInfo(member_name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    return path


# -- Debian packages ------------------------------------------------------------------------------
def _ar(members: list[tuple[str, bytes]]) -> bytes:
    out = bytearray(b"!<arch>\n")
    for name, data in members:
        header = (
            name.ljust(16)[:16] + "0".ljust(12) + "0".ljust(6) + "0".ljust(6) + "100644".ljust(8)
            + str(len(data)).ljust(10)
        ).encode("ascii") + b"`\n"
        out += header + data
        if len(data) % 2:
            out += b"\n"
    return bytes(out)


def _tar_bytes(files: dict[str, bytes], mode: str) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode=mode) as tar:
        for name, data in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o755 if name.endswith(("inst", "rm")) or data.startswith(b"#!") else 0o644
            tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def build_deb(dest: Path, *, name="hello", version="1.2.3-1", arch="amd64",
              depends="libc6 (>= 2.34), libssl3 | libssl1.1", scripts: dict[str, str] | None = None,
              control_extra: str = "", files: dict[str, bytes] | None = None) -> Path:
    control = (
        f"Package: {name}\nVersion: {version}\nArchitecture: {arch}\nMaintainer: Test <t@example.invalid>\n"
        f"Installed-Size: 42\nDepends: {depends}\nRecommends: hello-doc\nSection: utils\n"
        f"Homepage: https://example.invalid\nDescription: Test package\n second line of description\n"
        + control_extra
    )
    control_files = {"./control": control.encode()}
    for sname, body in (scripts or {}).items():
        control_files[f"./{sname}"] = body.encode()
    control_tar = _tar_bytes(control_files, "w:xz")
    data_tar = _tar_bytes({f"./{k.lstrip('./')}": v for k, v in (files or {"usr/bin/hello": b"#!/bin/sh\n"}).items()},
                          "w:gz")
    path = dest / f"{name}_{version}_{arch}.deb"
    path.write_bytes(_ar([("debian-binary", b"2.0\n"), ("control.tar.xz", control_tar),
                          ("data.tar.gz", data_tar)]))
    return path


# -- RPM packages ---------------------------------------------------------------------------------
STRING, INT32, STRING_ARRAY, BIN = 6, 4, 8, 7


def _rpm_header(entries: list[tuple[int, int, object]]) -> bytes:
    index, store = bytearray(), bytearray()
    for tag, typ, value in entries:
        if typ == INT32:
            while len(store) % 4:
                store += b"\0"
            values = value if isinstance(value, list) else [value]
            offset, count = len(store), len(values)
            store += struct.pack(f">{count}I", *values)
        elif typ == STRING:
            offset, count = len(store), 1
            store += str(value).encode() + b"\0"
        elif typ in (STRING_ARRAY, 9):  # 9 = I18NSTRING
            offset, count = len(store), len(value)  # type: ignore[arg-type]
            for item in value:  # type: ignore[union-attr]
                store += str(item).encode() + b"\0"
        else:
            offset, count = len(store), len(value)  # type: ignore[arg-type]
            store += bytes(value)  # type: ignore[arg-type]
        index += struct.pack(">iIiI", tag, typ, offset, count)
    return b"\x8e\xad\xe8\x01\0\0\0\0" + struct.pack(">II", len(entries), len(store)) + bytes(index) + bytes(store)


def build_rpm(dest: Path, *, name="hello", version="1.2.3", release="1", arch="x86_64",
              requires=("libc.so.6()(64bit)", "rpmlib(PayloadIsZstd)", "/bin/sh"),
              postin: str | None = "systemctl enable hello.service || :", signed=False,
              files: dict[str, bytes] | None = None, extra: tuple = ()) -> Path:
    lead = b"\xed\xab\xee\xdb\x03\x00" + struct.pack(">hh", 0, 1) + name.encode().ljust(66, b"\0")[:66] \
        + struct.pack(">hh", 1, 5) + b"\0" * 16
    sig_entries: list[tuple[int, int, object]] = [(1000, INT32, [123])]
    if signed:
        sig_entries.append((268, BIN, b"\x89" * 32))
    sig = _rpm_header(sig_entries)
    sig += b"\0" * ((8 - len(sig) % 8) % 8)
    flags = [0x1000000 if r.startswith("rpmlib(") else 0 for r in requires]
    entries: list[tuple[int, int, object]] = [
        (1000, STRING, name), (1001, STRING, version), (1002, STRING, release),
        (1004, STRING, "Test package"), (1009, INT32, [4096]), (1014, STRING, "MIT"),
        (1022, STRING, arch), (1049, STRING_ARRAY, list(requires)), (1048, INT32, flags),
        (1050, STRING_ARRAY, [""] * len(requires)), (1047, STRING_ARRAY, [name]),
        (1124, STRING, "cpio"), (1125, STRING, "zstd"),
    ]
    if postin is not None:
        entries += [(1024, STRING, postin), (1086, STRING, "/bin/sh")]
    entries += list(extra)  # (tag, type, value) triples: e.g. a %posttrans scriptlet and its program
    path = dest / f"{name}-{version}-{release}.{arch}.rpm"
    path.write_bytes(lead + sig + _rpm_header(entries) + (_cpio_zst(dest, files) if files else b"payload"))
    return path


def _cpio_zst(dest: Path, files: dict[str, bytes]) -> bytes:
    """A real RPM payload: a newc cpio archive, zstd-compressed."""
    import tempfile

    with tempfile.TemporaryDirectory(dir=dest) as tmp:
        for rel, data in files.items():
            f = Path(tmp) / rel.lstrip("./")
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_bytes(data)
            f.chmod(0o755 if data.startswith(b"#!") else 0o644)
        cpio = subprocess.run(["bsdtar", "--format", "newc", "-cf", "-", "-C", tmp, "."], check=True,
                              capture_output=True).stdout
    return subprocess.run(["zstd", "-q", "-c"], input=cpio, check=True, capture_output=True).stdout


