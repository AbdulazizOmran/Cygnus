def _elf_stub(update_info: str, signed: bool) -> bytes:
    shstrtab = b"\0.upd_info\0.sha256_sig\0.sig_key\0.shstrtab\0"
    upd = update_info.encode().ljust(1024, b"\0")
    sig = (b"-----BEGIN PGP SIGNATURE-----" if signed else b"").ljust(1024, b"\0")
    key = (b"-----BEGIN PGP PUBLIC KEY BLOCK-----" if signed else b"").ljust(8192, b"\0")
    data = bytearray(b"\0" * 64)
    offsets = {}
    for label, blob in (("upd", upd), ("sig", sig), ("key", key), ("str", shstrtab)):
        offsets[label] = len(data)
        data += blob
    while len(data) % 8:
        data += b"\0"
    shoff = len(data)

    def sh(name_off, sh_type, off, size):
        return struct.pack("<IIQQQQIIQQ", name_off, sh_type, 0, 0, off, size, 0, 0, 1, 0)

    table = sh(0, 0, 0, 0)
    table += sh(1, 7, offsets["upd"], len(upd))
    table += sh(11, 7, offsets["sig"], len(sig))
    table += sh(23, 7, offsets["key"], len(key))
    table += sh(32, 3, offsets["str"], len(shstrtab))
    ident = b"\x7fELF" + bytes([2, 1, 1, 0]) + b"AI\x02" + b"\0" * 5
    header = ident + struct.pack("<HHIQQQIHHHHHH", 2, 0x3E, 1, 0, 0, shoff, 0, 64, 0, 0, 64, 5, 4)
    data[:64] = header
    return bytes(data) + table


def build_appimage(dest: Path, *, update_info="zsync|https://example.invalid/Hello.AppImage.zsync",
                   signed=False, with_squashfs: bool | None = None, desktop: str = DESKTOP,
                   escape_symlink: bool = False, version: str = "2.5.0", app_id: str = "org.example.Hello") -> Path:
    """Create a fake type-2 AppImage. With mksquashfs available the payload is a real squashfs image."""
    desktop = desktop.replace("X-AppImage-Version=2.5.0", f"X-AppImage-Version={version}")
    appstream = APPSTREAM.replace('version="2.5.0"', f'version="{version}"').replace("org.example.Hello", app_id)
    path = dest / "Hello-x86_64.AppImage"
    runtime = _elf_stub(update_info, signed)
    mksquashfs = shutil.which("mksquashfs")
    if with_squashfs is None:
        with_squashfs = mksquashfs is not None
    if with_squashfs:
        if mksquashfs is None:
            raise RuntimeError("mksquashfs not available")
        root = dest / "appdir"
        (root / "usr/share/metainfo").mkdir(parents=True)
        (root / "usr/share/applications").mkdir(parents=True)
        (root / "usr/share/applications/hello.desktop").write_text(desktop)
        if escape_symlink:
            (root / "hello.desktop").symlink_to("/etc/passwd")
        else:
            (root / "hello.desktop").symlink_to("usr/share/applications/hello.desktop")
        (root / "hello.png").write_bytes(PNG_1PX)
        (root / ".DirIcon").symlink_to("hello.png")
        (root / f"usr/share/metainfo/{app_id}.appdata.xml").write_text(appstream)
        (root / "AppRun").write_text("#!/bin/sh\nexit 0\n")
        img = dest / "payload.squashfs"
        subprocess.run([mksquashfs, str(root), str(img), "-quiet", "-noappend", "-all-root"], check=True)
        payload = img.read_bytes()
    else:
        payload = b"hsqs" + b"\0" * 252
    path.write_bytes(runtime + payload)
    path.chmod(0o755)
    return path


